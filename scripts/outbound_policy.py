"""Generate fail-closed runtime routing; OS enforcement is installed separately."""

import ipaddress
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]


def load_outbound_policy():
    policy = yaml.safe_load((ROOT / "policy/outbound.yaml").read_text())
    if policy.get("version") != 1 or policy.get("proxy_group") != "Final":
        raise ValueError("unsupported outbound policy")
    for network in policy["local_networks"]:
        ipaddress.ip_network(network)
    return policy


def local_rule(rule, policy=None):
    policy = policy or load_outbound_policy()
    fields = rule.split(",")
    if len(fields) < 2:
        return False
    if fields[0] in {"DOMAIN", "DOMAIN-SUFFIX"}:
        return fields[1] in policy["local_domains"]
    if fields[0] in {"IP-CIDR", "IP-CIDR6"}:
        net = ipaddress.ip_network(fields[1])
        return any(net.version == allowed.version and net.subnet_of(allowed)
                   for allowed in map(ipaddress.ip_network, policy["local_networks"]))
    return False


def outbound_script():
    policy = load_outbound_policy()
    prefix = [f"DOMAIN-SUFFIX,{name},DIRECT" for name in policy["local_domains"]]
    prefix += [f"{'IP-CIDR6' if ':' in net else 'IP-CIDR'},{net},DIRECT,no-resolve"
               for net in policy["local_networks"]]
    prefix += ["DST-PORT,53,REJECT"]
    return '''
// Strict routing: a failed proxy must never reach a direct outbound.
function applyPersonalOutboundPolicy(config) {
  const policy = ''' + json.dumps(policy, ensure_ascii=False) + ''';
  if (!policy.enabled) return config;
  const localRules = ''' + json.dumps(prefix, ensure_ascii=False) + ''';
  const directGroups = new Set(policy.direct_groups);
  const unsafe = new Set(["DIRECT", "COMPATIBLE", "PASS"]);
  for (const node of config.proxies || []) {
    if (["direct", "compatible", "pass"].includes((node.type || "").toLowerCase())) unsafe.add(node.name);
  }
  const excludeTypes = (value) => Array.from(new Set([
    ...(value || "").split("|").filter(Boolean), "direct", "compatible", "pass"
  ])).join("|");
  for (const provider of Object.values(config["proxy-providers"] || {})) {
    provider["exclude-type"] = excludeTypes(provider["exclude-type"]);
  }
  const groups = config["proxy-groups"] || [];
  for (const group of groups) {
    if (directGroups.has(group.name)) continue;
    group["exclude-type"] = excludeTypes(group["exclude-type"]);
    group.proxies = (group.proxies || []).filter(name => !unsafe.has(name) && !directGroups.has(name));
    if (!group.proxies.includes("REJECT")) group.proxies.push("REJECT");
  }
  if (!groups.some(group => group.name === policy.proxy_group)) {
    groups.push({name: policy.proxy_group, type: "select", proxies: [
      ...(config.proxies || []).filter(node => !unsafe.has(node.name)).map(node => node.name), "REJECT"
    ], use: Object.keys(config["proxy-providers"] || {})});
  }
  config["proxy-groups"] = groups;
  const rules = [];
  for (const raw of config.rules || []) {
    if (localRules.includes(raw) || raw === "MATCH,REJECT") continue;
    // Guards generated by a previous application are rebuilt below.
    if (raw.startsWith("AND,((NETWORK,UDP),(") && raw.endsWith(")),REJECT")) continue;
    const fields = raw.split(",");
    const targetIndex = fields.length - (fields[fields.length - 1] === "no-resolve" ? 2 : 1);
    if (targetIndex < 1) continue;
    if (fields[0] === "RULE-SET" && /^(Personal-)?(GameDownloadCN|SteamCN)$/.test(fields[1])) {
      fields[targetIndex] = "🇨🇳 ChinaWebsites";
    }
    if (unsafe.has(fields[targetIndex]) && !(fields[0] === "GEOIP" && fields[1] === "CN")) {
      fields[targetIndex] = policy.proxy_group;
    }
    const target = fields[targetIndex];
    rules.push(fields.join(","));
    if (!directGroups.has(target) && !["DIRECT", "REJECT", "REJECT-DROP"].includes(target)
        && fields[0] !== "MATCH") {
      // Mihomo skips a rule when its node lacks UDP. Reject that same match
      // before a later domestic-IP/direct rule can accept the connection.
      const predicate = fields.slice(0, targetIndex).join(",");
      rules.push(`AND,((NETWORK,UDP),(${predicate})),REJECT`);
    }
  }
  if (!rules.some(rule => rule.startsWith("MATCH,"))) rules.push(`MATCH,${policy.proxy_group}`);
  // The final proxy can also lack UDP: never use the implicit DIRECT default.
  rules.push("MATCH,REJECT");
  config.rules = [...localRules, ...rules];
  config.mode = "rule";
  return config;
}
'''

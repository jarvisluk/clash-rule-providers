#!/usr/bin/env python3
"""Build a portable FlClash override from the current Clash Verge sources."""

import json
from pathlib import Path
import re
import sys

import yaml


POLICY_REPO = Path(__file__).resolve().parent.parent
VERGE = Path.home() / "Library/Application Support/io.github.clash-verge-rev.clash-verge-rev"


def read_yaml(path):
    return yaml.safe_load(Path(path).read_text())


def build(root=VERGE):
    providers = read_yaml(root / "profiles/Merge.yaml")["rule-providers"]
    for provider in providers.values():
        if provider.get("type") == "file":
            payload = read_yaml(root / provider["path"])["payload"]
            provider["type"] = "inline"
            provider["payload"] = payload
            provider.pop("path", None)

    # DNS is generated by the personal repository, never copied from GUI overrides.
    shared = read_yaml(POLICY_REPO / "mihomo/dns.yaml")
    dns = shared["dns"]
    ipv6 = shared["ipv6"]
    helper = (POLICY_REPO / "mihomo/dns-override.js").read_text().split("\nfunction main(config)")[0]

    standalone = (root / "profiles/Script.js").read_text()
    merged = (root / "profiles/sviiDJPlf3BL.js").read_text()
    def strip_dns_policy(script):
        script = re.sub(r"// BEGIN SHARED DNS POLICY.*?// END SHARED DNS POLICY\n?", "", script, flags=re.S)
        return script.replace("return applyPersonalDnsPolicy(config);", "return config;").replace("return applyPersonalDnsPolicy(config, true);", "return config;")
    standalone = strip_dns_policy(standalone)
    merged = strip_dns_policy(merged)
    standalone = re.sub(r"function main\(", "function buildStandaloneConfig(", standalone, count=1)
    merged = re.sub(r"function main\(", "function buildMergedConfig(", merged, count=1)

    header = (
        "// Generated by scripts/build_flclash_override.py.\n"
        "// Standalone subscriptions replace vendor groups; provider-only inputs use Merge All groups.\n"
        "const syncedRuleProviders = " + json.dumps(providers, ensure_ascii=False, indent=2) + ";\n"
        "const syncedDns = " + json.dumps(dns, ensure_ascii=False, indent=2) + ";\n"
        "const syncedIpv6 = " + json.dumps(ipv6) + ";\n\n"
    )
    entry = """function main(config) {
  const hasNodes = (config.proxies || []).some((node) =>
    node && node.name && !["direct", "reject"].includes(node.type)
      && !/剩余流量|套餐到期|距离下次|最新网址|remain:|used:|reset in:/i.test(node.name));
  const hasProviders = Object.keys(config["proxy-providers"] || {}).length > 0;
  if (!hasNodes && !hasProviders) return applyPersonalDnsPolicy(config);

  config["rule-providers"] = {
    ...(config["rule-providers"] || {}),
    ...JSON.parse(JSON.stringify(syncedRuleProviders)),
  };
  if (hasNodes) {
    config = buildStandaloneConfig(config, "FlClash");
  } else {
    config = buildStandaloneConfig(config, "Merge All");
    config = buildMergedConfig(config);
  }
  config.ipv6 = syncedIpv6;
  config.dns = JSON.parse(JSON.stringify(syncedDns));
  config.tun = {
    ...(config.tun || {}),
    "route-exclude-address": Array.from(new Set([
      ...((config.tun || {})["route-exclude-address"] || []),
      "100.64.0.0/10",
      "fd7a:115c:a1e0::/48",
    ])),
  };
  return applyPersonalDnsPolicy(config);
}

"""
    return header + entry + standalone + "\n" + merged + "\n" + helper


if __name__ == "__main__":
    output = Path(sys.argv[1]) if len(sys.argv) > 1 else VERGE / "profiles/FlClash-Override.js"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(build())
    print(f"Updated {output}")
